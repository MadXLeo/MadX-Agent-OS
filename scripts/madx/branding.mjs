// Product identity has one source. Generated output is committed for ordinary builds.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const brand = JSON.parse(fs.readFileSync(path.join(root, 'branding/product.json'), 'utf8'))
const write = process.argv.includes('--write')
const known = new Set(['--write', '--check'])
if (process.argv.slice(2).some(arg => !known.has(arg))) throw new Error('Use --write or --check')
if (brand.schemaVersion !== 1 || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(brand.slug) ||
    !/^\d+\.\d+\.\d+(?:-[a-z0-9.]+)?$/.test(brand.version)) throw new Error('Invalid product manifest')

const outputs = new Map()
outputs.set('apps/desktop/shared/product.ts', `// Generated by scripts/madx/branding.mjs from branding/product.json. Do not edit.\nexport const PRODUCT = ${JSON.stringify(brand, null, 2)} as const\n`)
outputs.set('linux/branding/product.json', `${JSON.stringify(brand, null, 2)}\n`)
const themeEngine = 'linux/bin/herald-os-theme'
outputs.set(themeEngine, fs.readFileSync(path.join(root, themeEngine), 'utf8').replace(/^DEFAULT = ".*"$/m, `DEFAULT = "${brand.appearance.linuxTheme}"`))
const isoPath = 'linux/image/iso.toml'
const iso = fs.readFileSync(path.join(root, isoPath), 'utf8').replace(/\n# Generated MadX ISO metadata[\s\S]*$/, '').trimEnd()
outputs.set(isoPath, `${iso}\n\n# Generated MadX ISO metadata; installation disk choices remain in Anaconda.\n[customizations.iso]\nvolume_id = "${brand.distribution.isoVolumeId}"\napplication_id = "${brand.name}"\npublisher = "${brand.ecosystem}"\n`)

for (const relative of ['package.json', 'apps/desktop/package.json']) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, relative), 'utf8'))
  pkg.version = brand.version
  pkg.description = `${brand.name}: an agent-native operating system powered by Hermes Agent.`
  if (relative === 'package.json') {
    pkg.name = brand.slug
    pkg.homepage = brand.repository
    pkg.repository.url = `${brand.repository}.git`
    pkg.bugs = `${brand.repository}/issues`
  } else {
    // Linux executable and app IDs remain compatibility contracts. Artifact consumers migrate together.
    pkg.productName = brand.name
    pkg.build.productName = brand.name
    pkg.build.executableName = brand.name
    pkg.build.artifactName = `${brand.distribution.artifactPrefix}-\${version}-\${os}-\${arch}.\${ext}`
    pkg.build.linux.artifactName = `${brand.distribution.artifactPrefix}-\${version}-linux-\${arch}.\${ext}`
    const linuxResources = pkg.build.linux.extraResources.find(resource => resource.to === 'herald-os-linux')
    if (!linuxResources.filter.includes('branding/**')) linuxResources.filter.push('branding/**')
    pkg.build.linux.desktop.entry.Name = brand.name
    const calendar = `${brand.name} shows today's events on the Overview, and gives their titles and times to Hermes when you turn on Pick up where you left off.`
    Object.assign(pkg.build.mac.extendInfo, {
      NSAppleEventsUsageDescription: `${brand.name} controls applications on your behalf when you ask it to.`,
      NSMicrophoneUsageDescription: `${brand.name} uses the microphone for voice input.`,
      NSCameraUsageDescription: `${brand.name} shows your camera in a bubble while you record the screen, when you turn it on.`,
      NSCalendarsFullAccessUsageDescription: calendar,
      NSCalendarsUsageDescription: calendar,
      NSLocalNetworkUsageDescription: `${brand.name} lets Hermes reach the devices on your local network that you set it up to use, such as a computer that runs your model.`
    })
  }
  outputs.set(relative, `${JSON.stringify(pkg, null, 2)}\n`)
}

// Only identity metadata changes in the existing lock. No dependency resolution or version changes.
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'))
lock.name = brand.slug
lock.version = brand.version
lock.packages[''].name = brand.slug
lock.packages[''].version = brand.version
lock.packages['apps/desktop'].version = brand.version
outputs.set('package-lock.json', `${JSON.stringify(lock, null, 2)}\n`)

const htmlPath = 'apps/desktop/index.html'
const html = fs.readFileSync(path.join(root, htmlPath), 'utf8').replace(/<title>[^<]*<\/title>/, `<title>${brand.name}</title>`)
outputs.set(htmlPath, html)

// niri matches product titles as identity. Accept the previous identity during an upgrade.
const escapeRegex = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const titles = `(${escapeRegex(brand.name)}|Herald OS)`
const appIds = `^(${[brand.slug, brand.name, 'herald-os', 'Herald OS'].map(escapeRegex).join('|')})$`
const niriPath = 'linux/niri/config.kdl'
const niri = fs.readFileSync(path.join(root, niriPath), 'utf8').split('\n').map(line => {
  if (line.includes('app-id=') && line.includes('herald-os')) {
    line = line.replace(/app-id=r#"[^"]+"#/, `app-id=r#"${appIds}"#`)
    line = line.replace(/title="\^(?:Herald OS|\([^)]*\|Herald OS\))/, `title="^${titles}`)
    line = line.replace(/title="\^(?:Herald Slides|\([^)]*\|Herald Slides\)) Audience/, `title="^(${escapeRegex(brand.apps.slides)}|Herald Slides) Audience`)
    line = line.replace(/Open in (?:Herald Canvas|\([^)]*\|Herald Canvas\))/, `Open in (${escapeRegex(brand.apps.canvas)}|Herald Canvas)`)
  }
  line = line.replace(/hotkey-overlay-title="([^"]*)"/g, (_, title) => `hotkey-overlay-title="${title.replace(/Herald OS|MadX Agent OS/g, brand.name)}"`)
  return line
}).join('\n')
outputs.set(niriPath, niri)

for (const directory of ['linux/image', 'linux/session']) {
  for (const name of fs.readdirSync(path.join(root, directory))) {
    if (!/\.(service|timer|desktop)$/.test(name) || !name.startsWith('herald-os')) continue
    const relative = `${directory}/${name}`
    const value = fs.readFileSync(path.join(root, relative), 'utf8')
      .replace(/^(Description|Name)=(?:Herald OS|MadX Agent OS)(.*)$/gm, (_, key, rest) => `${key}=${brand.name}${rest}`)
    outputs.set(relative, value)
  }
}
const plymouthPath = 'linux/plymouth/herald-os/herald-os.plymouth'
outputs.set(plymouthPath, fs.readFileSync(path.join(root, plymouthPath), 'utf8')
  .replace(/^Name=.*$/m, `Name=${brand.name}`)
  .replace(/^Description=.*$/m, `Description=${brand.name} boot splash`))

// SVG favicons cannot fetch external subresources. Embed the unchanged supplied image.
const supplied = fs.readFileSync(path.join(root, 'apps/desktop/src/assets/brand/madx-wordmark.png'))
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${brand.assets.monogramViewBox}"><title>${brand.name}</title><defs><clipPath id="mark"><path d="${brand.assets.monogramClip}"/></clipPath></defs><image clip-path="url(#mark)" href="data:image/png;base64,${supplied.toString('base64')}" width="2172" height="724"/></svg>\n`
outputs.set('apps/desktop/public/brand/madx-icon.svg', favicon)

const stale = []
for (const [relative, expected] of outputs) {
  const target = path.join(root, relative)
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') : ''
  const normalized = expected.replaceAll('\r\n', '\n')
  if (current === normalized) continue
  stale.push(relative)
  if (write) { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, normalized) }
}
// Native assets are committed exports, checked without requiring a browser on every build.
if (!write) {
  const assets = JSON.parse(fs.readFileSync(path.join(root, 'branding/assets.json'), 'utf8'))
  const hash = data => crypto.createHash('sha256').update(data).digest('hex')
  if (assets.sourceSha256 !== hash(supplied) || assets.viewport !== brand.assets.monogramViewBox || assets.clip !== brand.assets.monogramClip) stale.push('branding/assets.json (re-export artwork)')
  if (!supplied.equals(fs.readFileSync(path.join(root, 'apps/desktop/public/brand/madx-wordmark.png')))) stale.push('public wordmark')
  for (const [relative, expected] of Object.entries(assets.files)) {
    if (hash(fs.readFileSync(path.join(root, relative))) !== expected) stale.push(relative)
  }
}
if (stale.length && !write) {
  console.error(`Product identity is stale: ${stale.join(', ')}. Run npm run branding:sync.`)
  process.exitCode = 1
} else {
  console.log(write ? `Updated ${stale.length} product identity files.` : 'Product identity files are synchronized.')
}
